#!/bin/sh
# Writes Dockerfile.cloud (Dockerfile.base + Dockerfile in one) for builders without the local base tag,
# e.g. KOOMPI Cloud deploy_github (dockerfile docker/selkies/Dockerfile.cloud, context ./, port 8080). Rerun after editing either.
cd "$(dirname "$0")"
{ echo "# Generated by docker/selkies/cloud.sh from Dockerfile.base + Dockerfile: edit those, then rerun it."
  grep -v '^#' Dockerfile.base
  grep -v -e '^#' -e '^ARG BASE' -e '^FROM' Dockerfile; } > Dockerfile.cloud
